// Запит до GPT зі строгою JSON-схемою відповіді.
export async function askJson<T>(system: string, user: string, name: string, schema: object): Promise<T> {
  const res = await openai.chat.completions.create({
    model: MODEL,
    messages: [
      { role: "system", content: system },
      { role: "user", content: user },
    ],
    response_format: { type: "json_schema", json_schema: { name, strict: true, schema: schema as Record<string, unknown> } },
  });

  const raw = res.choices[0]?.message.content;
  if (!raw) throw new Error(`GPT повернув порожню відповідь (${name})`);
  return JSON.parse(raw) as T;
}
