// Фактчек рівня 1: звіряємо готовий пост з оригінальною статтею, з якої він написаний.
// Ловить вигадане, перекручене, перебільшене й пропущений важливий контекст. Помилок самого джерела не бачить.
import { askJson, LANGUAGE } from "./gpt.ts";

export interface FactCheck {
  verdict: "ok" | "fixed" | "reject";
  issues: string[]; // коротко, що було не так (порожньо, якщо ok)
  post: string; // виправлений пост (або той самий)
  hook: string; // виправлений гачок (або той самий / порожній)
}

const SYSTEM_PROMPT = `Ти фактчекер українського Telegram/Threads-каналу. Тобі дають ОРИГІНАЛЬНУ статтю і ПОСТ, написаний за нею
(і, можливо, короткий гачок для Threads). Перевір пост речення за реченням проти оригіналу.

Шукай:
- вигадане: факти, цифри, назви, дати, яких в оригіналі немає;
- перекручене: неточні цифри чи умови («до 25 000 €» → «25 000 €», «бета для частини користувачів» → «для всіх»),
  сплутано, хто що зробив;
- перебільшене: «вперше», «тепер можна», «революція», якщо в оригіналі це не так;
- пропущений важливий контекст: якщо оригінал каже, що схоже вже існувало (в іншій програмі, давно відомий спосіб),
  або є важливе обмеження (платно, лише в США, лише бета), а пост подає це як беззастережну новинку.
Дрібниці стилю й тону НЕ чіпай — ти перевіряєш факти, а не переписуєш текст.

Порядок роботи:
1. Спершу заповни з ОРИГІНАЛУ: what_is_new — що саме тут нове (одним реченням); existed_before — що з цього вже існувало
   раніше чи в інших програмах, якщо оригінал про це каже (інакше порожньо); limits — важливі обмеження (платно, бета,
   лише для частини країн/користувачів), якщо є (інакше порожньо).
2. Перевір, чи пост чесно передає саме це. Якщо existed_before не порожнє, а пост подає річ як беззастережно нову
   («тепер можна…», «вперше…») і не згадує, що так уже можна було, — це ОБОВ'ЯЗКОВО помилка: виправ, додавши
   одне коротке речення про те, що існувало раніше, і уточнивши, що саме нове. Так само з limits.

verdict:
- "ok" — проблем немає; post і hook поверни без змін;
- "fixed" — були проблеми, ти їх виправив мінімальними правками (зберігаючи тон, довжину, абзаци й **жирне**);
- "reject" — головна думка поста не підтверджується оригіналом або перекручена так, що виправити = написати заново.
issues — коротко українською, що було не так (по 3–10 слів на пункт), порожній список якщо ok.
У виправленнях дотримуйся правил:
${LANGUAGE}`;

const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["what_is_new", "existed_before", "limits", "verdict", "issues", "post", "hook"],
  properties: {
    what_is_new: { type: "string" },
    existed_before: { type: "string" },
    limits: { type: "string" },
    verdict: { type: "string", enum: ["ok", "fixed", "reject"] },
    issues: { type: "array", items: { type: "string" } },
    post: { type: "string" },
    hook: { type: "string" },
  },
} as const;

// noNovelty — для постів про SkyNovix: правило «що існувало раніше» тут шкодить (фактчек дописував «на інших платформах
// таке вже було», 2026-10-25)
export async function factCheck(source: string, title: string, original: string, post: string, hook = "", opts: { noNovelty?: boolean } = {}): Promise<FactCheck> {
  const r = await askJson<FactCheck>(
    opts.noNovelty
      ? `${SYSTEM_PROMPT}\n\nДЛЯ ЦЬОГО ПОСТА: пункт про existed_before НЕ застосовуй — не додавай речень про те, що щось існувало раніше чи є на інших платформах. Перевіряй лише, чи немає вигаданого й перекрученого.`
      : SYSTEM_PROMPT,
    `ОРИГІНАЛ (${source}): ${title}\n\n${original}\n\n=====\n\nПОСТ:\n${post}\n\n=====\n\nГАЧОК:\n${hook || "(немає)"}`,
    "fact_check",
    SCHEMA,
  );
  // Підстраховка: якщо "fixed", але пост порожній — краще не надсилати
  if (r.verdict === "fixed" && !r.post.trim()) return { ...r, verdict: "reject" };
  return { ...r, post: r.verdict === "ok" ? post : r.post.trim(), hook: r.verdict === "ok" ? hook : r.hook.trim() };
}

// Рядок для службової частини під лінією
export function factNote(fc: FactCheck): string | null {
  return fc.verdict === "fixed" ? `✏️ фактчек виправив: ${fc.issues.join("; ")}` : null;
}
